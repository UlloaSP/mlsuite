-- Schemas: versioned form and output contracts, the models each version binds, the drafts being
-- edited, and the bookmarks that pin a version.

CREATE TABLE schema (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema PRIMARY KEY,
    organization_id BIGINT NOT NULL CONSTRAINT fk_schema_org REFERENCES organization (id),
    name VARCHAR(180) NOT NULL CONSTRAINT ck_schema_name_present CHECK (btrim(name) <> ''),
    description VARCHAR(800),
    archived_at TIMESTAMPTZ,
    -- Set under the schema's lock when a purge of it is asked for, and never cleared.
    purging_at TIMESTAMPTZ,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_org_id UNIQUE (organization_id, id));

CREATE UNIQUE INDEX uq_schema_org_name ON schema (organization_id, lower(name));
CREATE INDEX idx_search_schema_name_trgm ON schema USING GIN (lower(name) gin_trgm_ops);

-- A snapshot of a schema, written once with its bindings. It carries its schema's organization.
CREATE TABLE schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_version PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    schema_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL CONSTRAINT ck_schema_version_number CHECK (version_number >= 1),
    name VARCHAR(180),
    form_schema JSONB NOT NULL,
    -- The document's identity, as artifact_sha256 is a model's: what a run was computed against.
    -- (the bytes of its text, backslashes kept as written: a plain bytea cast would read them as escapes)
    form_schema_sha256 VARCHAR(64) NOT NULL
        GENERATED ALWAYS AS (encode(sha256(decode(replace(form_schema::text, '\', '\\'), 'escape')), 'hex')) STORED,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_version_created_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    -- The transaction that wrote it (top-level, also inside a savepoint): its bindings are written there.
    created_xact XID8 NOT NULL DEFAULT pg_current_xact_id(),
    CONSTRAINT uq_schema_version_schema_version UNIQUE (schema_id, version_number),
    CONSTRAINT uq_schema_version_schema_id UNIQUE (schema_id, id),
    CONSTRAINT uq_schema_version_org_id UNIQUE (organization_id, id),
    CONSTRAINT fk_schema_version_schema FOREIGN KEY (organization_id, schema_id)
        REFERENCES schema (organization_id, id));

CREATE UNIQUE INDEX uq_schema_version_schema_name ON schema_version (schema_id, lower(name)) WHERE name IS NOT NULL;

-- A snapshot is written once: what it belongs to, its number and its document never change.
CREATE TRIGGER trg_schema_version_fixed BEFORE UPDATE OF organization_id, schema_id, version_number, form_schema,
    created_xact ON schema_version FOR EACH ROW
    WHEN ((OLD.organization_id, OLD.schema_id, OLD.version_number, OLD.form_schema, OLD.created_xact)
        IS DISTINCT FROM (NEW.organization_id, NEW.schema_id, NEW.version_number, NEW.form_schema, NEW.created_xact))
    EXECUTE FUNCTION refuse_change('ck_schema_version_fixed');

-- A snapshot binds only models of its own organization.
CREATE TABLE schema_model_binding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_model_binding PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    schema_version_id BIGINT NOT NULL,
    model_id BIGINT NOT NULL,
    plugin_policy JSONB,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_binding_created_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_binding_model UNIQUE (schema_version_id, model_id),
    CONSTRAINT fk_schema_binding_version FOREIGN KEY (organization_id, schema_version_id)
        REFERENCES schema_version (organization_id, id),
    CONSTRAINT fk_schema_binding_model FOREIGN KEY (organization_id, model_id) REFERENCES model (organization_id, id));

CREATE INDEX idx_schema_binding_model ON schema_model_binding (organization_id, model_id);

-- A snapshot's parts (the models it binds, the plugins it renders with) are written in the
-- transaction that writes the snapshot and never change: whatever pins the snapshot (a run, a
-- bookmark, a job, a review) keeps them. They are removed only while the snapshot has no runs: with
-- an unused schema, or by a purge, which removes runs first. The trigger names the constraint.
CREATE FUNCTION snapshot_part_is_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE'
        OR (TG_OP = 'INSERT' AND NOT EXISTS (SELECT 1 FROM schema_version
            WHERE id = NEW.schema_version_id AND created_xact = pg_current_xact_id()))
        OR (TG_OP = 'DELETE' AND EXISTS (SELECT 1 FROM prediction_run WHERE schema_version_id = OLD.schema_version_id)) THEN
        RAISE EXCEPTION 'A snapshot''s % cannot change once it is written: violates check constraint "%"',
            TG_TABLE_NAME, TG_ARGV[0] USING ERRCODE = 'check_violation',
            CONSTRAINT = TG_ARGV[0], TABLE = TG_TABLE_NAME;
    END IF;
    RETURN CASE TG_OP WHEN 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER trg_schema_model_binding_fixed BEFORE INSERT OR UPDATE OR DELETE ON schema_model_binding
    FOR EACH ROW EXECUTE FUNCTION snapshot_part_is_fixed('ck_schema_binding_fixed');

-- A snapshot binds at least one model by the end of the transaction that writes it.
CREATE FUNCTION schema_version_binds_a_model() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM schema_version WHERE id = NEW.id)
        AND NOT EXISTS (SELECT 1 FROM schema_model_binding WHERE schema_version_id = NEW.id) THEN
        RAISE EXCEPTION 'A snapshot binds at least one model: violates check constraint "ck_schema_version_bound"' USING ERRCODE = 'check_violation',
            CONSTRAINT = 'ck_schema_version_bound', TABLE = 'schema_version';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_schema_version_bound AFTER INSERT ON schema_version
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION schema_version_binds_a_model();

-- The plugin that draws each custom kind a snapshot's form names, fixed when the snapshot is
-- published, so the snapshot renders as it was published whatever the organization's library holds
-- later. A plugin a snapshot uses cannot be deleted. Written with the snapshot, like its bindings.
CREATE TABLE schema_version_plugin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_version_plugin PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    schema_version_id BIGINT NOT NULL,
    plugin_metadata_id BIGINT NOT NULL,
    CONSTRAINT uq_schema_version_plugin UNIQUE (schema_version_id, plugin_metadata_id),
    CONSTRAINT fk_schema_version_plugin_version FOREIGN KEY (organization_id, schema_version_id)
        REFERENCES schema_version (organization_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_schema_version_plugin_plugin FOREIGN KEY (organization_id, plugin_metadata_id)
        REFERENCES plugin_metadata (organization_id, id));

CREATE INDEX idx_schema_version_plugin_plugin ON schema_version_plugin (organization_id, plugin_metadata_id);
CREATE TRIGGER trg_schema_version_plugin_fixed BEFORE INSERT OR UPDATE OR DELETE ON schema_version_plugin
    FOR EACH ROW EXECUTE FUNCTION snapshot_part_is_fixed('ck_schema_version_plugin_fixed');


-- A draft stays on snapshots of its own schema; publishing records the snapshot it became, which
-- no other draft became. A draft
-- is a document still being written: its bindings are checked against the organization's models
-- when it is published as a snapshot, whose bindings are rows. A snapshot's bindings never change,
-- so what the draft started from is its base snapshot's.
CREATE TABLE schema_draft (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_draft PRIMARY KEY,
    schema_id BIGINT NOT NULL CONSTRAINT fk_schema_draft_schema REFERENCES schema (id),
    base_version_id BIGINT NOT NULL,
    published_version_id BIGINT,
    name VARCHAR(180) NOT NULL CONSTRAINT ck_schema_draft_name_present CHECK (btrim(name) <> ''),
    status VARCHAR(32) NOT NULL CONSTRAINT ck_schema_draft_status CHECK (status IN ('DRAFT', 'CONFLICT', 'PUBLISHED')),
    lock_version BIGINT NOT NULL DEFAULT 0,
    form_schema JSONB NOT NULL,
    bindings JSONB NOT NULL,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_draft_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_draft_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_schema_draft_base FOREIGN KEY (schema_id, base_version_id) REFERENCES schema_version (schema_id, id),
    CONSTRAINT fk_schema_draft_published FOREIGN KEY (schema_id, published_version_id)
        REFERENCES schema_version (schema_id, id),
    CONSTRAINT uq_schema_draft_published UNIQUE (published_version_id),
    CONSTRAINT ck_schema_draft_published_version CHECK ((status = 'PUBLISHED') = (published_version_id IS NOT NULL)));

CREATE INDEX idx_schema_draft_base ON schema_draft (schema_id, base_version_id);

-- A bookmark describes itself: in its schema's repository and on its public page. It is private
-- until a member publishes it; public_id is assigned on the first publish or when an API client is
-- given the bookmark, and kept afterwards, so a shared /explore link survives unpublishing. A
-- published bookmark may carry a note for its visitors: a paper, a DOI, terms of use.
CREATE TABLE schema_bookmark (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_bookmark PRIMARY KEY,
    schema_id BIGINT NOT NULL CONSTRAINT fk_schema_bookmark_schema REFERENCES schema (id),
    schema_version_id BIGINT NOT NULL,
    name VARCHAR(180) NOT NULL CONSTRAINT ck_schema_bookmark_name_present CHECK (btrim(name) <> ''),
    description VARCHAR(800),
    visibility VARCHAR(16) NOT NULL DEFAULT 'PRIVATE'
        CONSTRAINT ck_schema_bookmark_visibility CHECK (visibility IN ('PRIVATE', 'PUBLIC')),
    public_id VARCHAR(36) CONSTRAINT uq_schema_bookmark_public_id UNIQUE,
    publication_note VARCHAR(1000),
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_bookmark_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_bookmark_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_bookmark_schema_id UNIQUE (schema_id, id),
    CONSTRAINT uq_schema_bookmark_id_visibility UNIQUE (id, visibility),
    CONSTRAINT fk_schema_bookmark_version FOREIGN KEY (schema_id, schema_version_id) REFERENCES schema_version (schema_id, id),
    CONSTRAINT ck_schema_bookmark_public_has_id CHECK (visibility = 'PRIVATE' OR public_id IS NOT NULL));

CREATE UNIQUE INDEX uq_schema_bookmark_schema_name ON schema_bookmark (schema_id, lower(name));
CREATE INDEX idx_schema_bookmark_version ON schema_bookmark (schema_version_id);

-- The bookmarks a person keeps at the top of their profile, at most six, in the order of their
-- slots. A bookmark is pinned once, by the owner of its personal account, and only while it is
-- public: unpublishing it takes its pins down in the same transaction (the key is checked at commit).
-- The slot is unique only at commit, so a reorder can swap two pins in place.
CREATE TABLE profile_pin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_profile_pin PRIMARY KEY,
    schema_bookmark_id BIGINT NOT NULL,
    bookmark_visibility VARCHAR(16) NOT NULL GENERATED ALWAYS AS ('PUBLIC') STORED,
    user_id BIGINT NOT NULL CONSTRAINT fk_profile_pin_user REFERENCES app_user (id) ON DELETE CASCADE,
    slot INTEGER NOT NULL CONSTRAINT ck_profile_pin_slot CHECK (slot BETWEEN 0 AND 5),
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_profile_pin_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_profile_pin_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_profile_pin_bookmark UNIQUE (user_id, schema_bookmark_id),
    CONSTRAINT fk_profile_pin_bookmark FOREIGN KEY (schema_bookmark_id, bookmark_visibility)
        REFERENCES schema_bookmark (id, visibility) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_profile_pin_slot UNIQUE (user_id, slot) DEFERRABLE INITIALLY DEFERRED);

CREATE INDEX idx_profile_pin_bookmark ON profile_pin (schema_bookmark_id, bookmark_visibility);

