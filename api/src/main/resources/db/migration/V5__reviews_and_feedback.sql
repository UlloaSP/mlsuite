-- Reviews of a schema version's runs, who answers them, and the answers themselves.

-- A review stays on a snapshot of its own schema in its own organization.
CREATE TABLE schema_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_review PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL CONSTRAINT uq_schema_review_public_id UNIQUE,
    organization_id BIGINT NOT NULL CONSTRAINT fk_schema_review_org REFERENCES organization (id),
    schema_id BIGINT NOT NULL,
    schema_version_id BIGINT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_review_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_review_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_review_id_version UNIQUE (id, schema_version_id),
    CONSTRAINT uq_schema_review_org_id UNIQUE (organization_id, id),
    CONSTRAINT fk_schema_review_schema FOREIGN KEY (organization_id, schema_id) REFERENCES schema (organization_id, id),
    CONSTRAINT fk_schema_review_version FOREIGN KEY (schema_id, schema_version_id) REFERENCES schema_version (schema_id, id));

CREATE INDEX idx_schema_review_schema ON schema_review (organization_id, schema_id);
CREATE INDEX idx_schema_review_version ON schema_review (schema_id, schema_version_id);

-- A reviewer is a member of the review's organization; the row carries the review's organization.
-- A reviewer who is gone has nothing left to do in a review; the answers they gave stay in it.
CREATE TABLE schema_review_assignee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_review_assignee PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    schema_review_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    -- Names the membership while it is active: removing the member removes the assignment first.
    membership_status VARCHAR(32) NOT NULL GENERATED ALWAYS AS ('ACTIVE') STORED,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_review_assignee_created_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_review_assignee UNIQUE (schema_review_id, user_id),
    CONSTRAINT fk_review_assignee_review FOREIGN KEY (organization_id, schema_review_id)
        REFERENCES schema_review (organization_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_review_assignee_member FOREIGN KEY (organization_id, user_id, membership_status)
        REFERENCES organization_membership (organization_id, user_id, status) ON DELETE CASCADE);

CREATE INDEX idx_schema_review_assignee_member ON schema_review_assignee (organization_id, user_id);
CREATE INDEX idx_schema_review_assignee_user ON schema_review_assignee (user_id);

-- A review covers only runs of the snapshot it reviews: the row carries the review's snapshot.
CREATE TABLE schema_review_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_review_run PRIMARY KEY,
    public_id VARCHAR(36) NOT NULL CONSTRAINT uq_schema_review_run_public_id UNIQUE,
    schema_version_id BIGINT NOT NULL,
    schema_review_id BIGINT NOT NULL,
    prediction_run_id BIGINT NOT NULL,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_review_run_created_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_review_run UNIQUE (schema_review_id, prediction_run_id),
    CONSTRAINT uq_schema_review_run_review_id UNIQUE (schema_review_id, id),
    CONSTRAINT fk_schema_review_run_review FOREIGN KEY (schema_review_id, schema_version_id)
        REFERENCES schema_review (id, schema_version_id) ON DELETE CASCADE,
    CONSTRAINT fk_schema_review_run_prediction FOREIGN KEY (schema_version_id, prediction_run_id)
        REFERENCES prediction_run (schema_version_id, id));

CREATE INDEX idx_schema_review_run_prediction ON schema_review_run (schema_version_id, prediction_run_id);

-- A reviewer's submission of their answers on one run of a review: who, and when. Only a reviewer
-- of that review submits; the row carries the review, and leaves with its reviewer.
CREATE TABLE schema_review_run_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_review_run_submission PRIMARY KEY,
    schema_review_id BIGINT NOT NULL,
    schema_review_run_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_review_run_submission UNIQUE (schema_review_run_id, user_id),
    CONSTRAINT fk_schema_review_submission_run FOREIGN KEY (schema_review_id, schema_review_run_id)
        REFERENCES schema_review_run (schema_review_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_schema_review_submission_assignee FOREIGN KEY (schema_review_id, user_id)
        REFERENCES schema_review_assignee (schema_review_id, user_id) ON DELETE CASCADE);

CREATE INDEX idx_schema_review_submission_assignee ON schema_review_run_submission (schema_review_id, user_id);

-- An answer about a result, by its author: a member or a visitor. An answer given in a review
-- belongs to that review, so removing a reviewer's response to one review leaves their answers in
-- other reviews and on the public page as they were; answers given elsewhere (a public page) belong
-- to no review. An author answers each question once per review, and once outside any review; the
-- author outlives their account, so this holds after it is deleted. An answer in a review is about
-- a run the review covers: the row carries its result's run. A review is deleted whole, with its
-- reviewers, runs, submissions, answers and their history; otherwise answers leave only by being
-- deleted, so whatever removes a review's run removes its answers first.
-- question_index is which question of its type it answers.
CREATE TABLE prediction_result_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_prediction_result_feedback PRIMARY KEY,
    prediction_run_id BIGINT NOT NULL,
    prediction_result_id BIGINT NOT NULL,
    schema_review_id BIGINT,
    feedback_type VARCHAR(32) NOT NULL CONSTRAINT ck_result_feedback_type CHECK (feedback_type IN ('OUTPUT', 'EXPLANATION')),
    question_index INTEGER NOT NULL CONSTRAINT ck_result_feedback_question CHECK (question_index >= 0),
    data_value JSONB NOT NULL,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_result_feedback_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_result_feedback_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    -- An answer is changed only by its author.
    CONSTRAINT ck_result_feedback_own CHECK (updated_by_principal_id = created_by_principal_id),
    CONSTRAINT fk_result_feedback_result FOREIGN KEY (prediction_run_id, prediction_result_id)
        REFERENCES prediction_result (prediction_run_id, id),
    CONSTRAINT fk_result_feedback_review_run FOREIGN KEY (schema_review_id, prediction_run_id)
        REFERENCES schema_review_run (schema_review_id, prediction_run_id),
    CONSTRAINT fk_result_feedback_review FOREIGN KEY (schema_review_id) REFERENCES schema_review (id) ON DELETE CASCADE);

CREATE UNIQUE INDEX uq_result_feedback_author ON prediction_result_feedback
    (prediction_result_id, feedback_type, question_index, created_by_principal_id, schema_review_id) NULLS NOT DISTINCT;
CREATE INDEX idx_result_feedback_run ON prediction_result_feedback (prediction_run_id);
CREATE INDEX idx_result_feedback_review_run ON prediction_result_feedback (schema_review_id, prediction_run_id);
CREATE INDEX idx_result_feedback_created_by ON prediction_result_feedback (created_by_principal_id);

-- An answer given in a review is its reviewer's: its author is assigned to the review when it is
-- written (an assignment may end later; the answer stays).
CREATE FUNCTION result_feedback_by_a_reviewer() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM schema_review_assignee a JOIN principal p ON p.user_id = a.user_id
            WHERE a.schema_review_id = NEW.schema_review_id AND p.id = NEW.created_by_principal_id) THEN
        RAISE EXCEPTION 'Only a reviewer of the review answers in it: violates check constraint "ck_result_feedback_reviewer"' USING ERRCODE = 'check_violation',
            CONSTRAINT = 'ck_result_feedback_reviewer', TABLE = 'prediction_result_feedback';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_result_feedback_reviewer BEFORE INSERT ON prediction_result_feedback FOR EACH ROW
    WHEN (NEW.schema_review_id IS NOT NULL) EXECUTE FUNCTION result_feedback_by_a_reviewer();

-- What an answer is about and whose it is never change; only what it says (and who said it last).
CREATE TRIGGER trg_result_feedback_fixed BEFORE UPDATE ON prediction_result_feedback FOR EACH ROW
    WHEN ((OLD.prediction_run_id, OLD.prediction_result_id, OLD.schema_review_id, OLD.feedback_type, OLD.question_index,
        OLD.created_by_principal_id, OLD.created_at)
        IS DISTINCT FROM (NEW.prediction_run_id, NEW.prediction_result_id, NEW.schema_review_id, NEW.feedback_type,
        NEW.question_index, NEW.created_by_principal_id, NEW.created_at))
    EXECUTE FUNCTION refuse_change('ck_result_feedback_fixed');


-- Every change of an answer, kept when the answer changes again or is removed: whose answer it was,
-- what it said and who changed it. Written by the answers' own trigger, below. An answer removed with its run leaves one DELETED revision, so
-- the removal stays on record once the result is gone: the revision keeps the answer's and the
-- result's ids as plain values, and goes only with its snapshot or its review.
CREATE TABLE prediction_result_feedback_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_prediction_result_feedback_revision PRIMARY KEY,
    feedback_id BIGINT NOT NULL,
    prediction_result_id BIGINT NOT NULL,
    schema_version_id BIGINT NOT NULL CONSTRAINT fk_feedback_revision_version REFERENCES schema_version (id) ON DELETE CASCADE,
    schema_review_id BIGINT,
    author_principal_id BIGINT NOT NULL CONSTRAINT fk_feedback_revision_author REFERENCES principal (id),
    feedback_type VARCHAR(32) NOT NULL CONSTRAINT ck_feedback_revision_type CHECK (feedback_type IN ('OUTPUT', 'EXPLANATION')),
    question_index INTEGER NOT NULL CONSTRAINT ck_feedback_revision_question CHECK (question_index >= 0),
    data_value JSONB,
    change_kind VARCHAR(16) NOT NULL CONSTRAINT ck_feedback_revision_change CHECK (change_kind IN ('CREATED', 'UPDATED', 'DELETED')),
    changed_by_principal_id BIGINT NOT NULL CONSTRAINT fk_feedback_revision_changed_by REFERENCES principal (id),
    changed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_feedback_revision_value CHECK ((change_kind = 'DELETED') = (data_value IS NULL)),
    -- A review's answers are about its snapshot's runs.
    CONSTRAINT fk_feedback_revision_review FOREIGN KEY (schema_review_id, schema_version_id)
        REFERENCES schema_review (id, schema_version_id) ON DELETE CASCADE);

CREATE INDEX idx_feedback_revision_result ON prediction_result_feedback_revision (prediction_result_id, id);
CREATE INDEX idx_feedback_revision_version ON prediction_result_feedback_revision (schema_version_id);
CREATE INDEX idx_feedback_revision_review ON prediction_result_feedback_revision (schema_review_id, schema_version_id);
CREATE INDEX idx_feedback_revision_feedback ON prediction_result_feedback_revision (feedback_id, id);

-- Every change of an answer, whoever writes it, makes its run's projection stale and is written to
-- the answer's history, in the same transaction. Who changed it is the answer's updated_by for a write; for a removal it is the principal the
-- transaction names in app.principal_id (SET LOCAL), and a removal that names no one is refused.
-- Removing the answers of a snapshot a purge destroys, or of a review being deleted (which takes
-- them with it), records nothing: their history goes with them.
CREATE FUNCTION result_feedback_changed() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    answer prediction_result_feedback%ROWTYPE;
    actor BIGINT;
    version_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        answer := OLD;
        actor := nullif(current_setting('app.principal_id', true), '')::bigint;
    ELSE
        answer := NEW;
        actor := NEW.updated_by_principal_id;
    END IF;
    INSERT INTO prediction_run_projection (prediction_run_id, answer_changes) VALUES (answer.prediction_run_id, 1)
    ON CONFLICT (prediction_run_id) DO UPDATE SET answer_changes = prediction_run_projection.answer_changes + 1;
    SELECT schema_version_id INTO version_id FROM prediction_result WHERE id = answer.prediction_result_id;
    IF TG_OP = 'DELETE' AND (EXISTS (SELECT 1 FROM purge_job_version WHERE schema_version_id = version_id)
            OR (answer.schema_review_id IS NOT NULL
                AND NOT EXISTS (SELECT 1 FROM schema_review WHERE id = answer.schema_review_id))) THEN
        RETURN NULL;
    END IF;
    IF actor IS NULL THEN
        RAISE EXCEPTION 'Removing an answer names who removes it: violates check constraint "ck_feedback_revision_actor"' USING ERRCODE = 'check_violation',
            CONSTRAINT = 'ck_feedback_revision_actor', TABLE = 'prediction_result_feedback';
    END IF;
    INSERT INTO prediction_result_feedback_revision (feedback_id, prediction_result_id, schema_version_id,
        schema_review_id, author_principal_id, feedback_type, question_index, data_value, change_kind,
        changed_by_principal_id, changed_at)
    VALUES (answer.id, answer.prediction_result_id, version_id, answer.schema_review_id, answer.created_by_principal_id,
        answer.feedback_type, answer.question_index, CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE answer.data_value END,
        CASE TG_OP WHEN 'INSERT' THEN 'CREATED' WHEN 'UPDATE' THEN 'UPDATED' ELSE 'DELETED' END, actor, now());
    RETURN NULL;
END $$;
CREATE TRIGGER trg_result_feedback_changed AFTER INSERT OR UPDATE OR DELETE ON prediction_result_feedback
    FOR EACH ROW EXECUTE FUNCTION result_feedback_changed();

CREATE TRIGGER trg_schema_review_not_purging BEFORE INSERT ON schema_review FOR EACH ROW
    EXECUTE FUNCTION refuse_under_purge('schema', 'schema_id');
