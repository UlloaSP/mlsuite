-- What a person says about themselves on their profile. The avatar replaces avatar_url, which
-- nothing ever wrote: like an organization's logo it lives in its own table, read through an
-- address versioned by avatar_updated_at. A profile is public unless its owner says otherwise.
ALTER TABLE app_user
    DROP COLUMN avatar_url,
    ADD COLUMN bio VARCHAR(280),
    ADD COLUMN location VARCHAR(100),
    ADD COLUMN website VARCHAR(255),
    ADD COLUMN company VARCHAR(100),
    ADD COLUMN profile_links VARCHAR(255)[] NOT NULL DEFAULT '{}',
    ADD COLUMN profile_public BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN profile_shows_organizations BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN avatar_updated_at TIMESTAMPTZ;

CREATE TABLE user_avatar (
    user_id BIGINT PRIMARY KEY CONSTRAINT fk_user_avatar_user REFERENCES app_user ON DELETE CASCADE,
    content BYTEA NOT NULL, content_type VARCHAR(40) NOT NULL, updated_at TIMESTAMPTZ NOT NULL);

-- The bookmarks a person keeps at the top of their profile, at most six, in the order of their
-- slots. A bookmark is pinned once, by the owner of its personal account. The slot is unique only
-- at commit, so a reorder can swap two pins in place.
CREATE TABLE profile_pin (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_bookmark_id BIGINT NOT NULL CONSTRAINT fk_profile_pin_bookmark REFERENCES schema_bookmark ON DELETE CASCADE,
    user_id BIGINT NOT NULL CONSTRAINT fk_profile_pin_user REFERENCES app_user ON DELETE CASCADE,
    slot INTEGER NOT NULL CONSTRAINT ck_profile_pin_slot CHECK (slot BETWEEN 0 AND 5),
    CONSTRAINT uq_profile_pin_bookmark UNIQUE (schema_bookmark_id),
    CONSTRAINT uq_profile_pin_slot UNIQUE (user_id, slot) DEFERRABLE INITIALLY DEFERRED);
