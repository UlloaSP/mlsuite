-- An answer given in a review belongs to that review, so removing a reviewer's response to one
-- review leaves their answers in other reviews and on the public page as they were. Answers given
-- elsewhere (a public page) belong to no review.
ALTER TABLE prediction_result_feedback ADD COLUMN schema_review_id BIGINT
    CONSTRAINT fk_result_feedback_review REFERENCES schema_review (id) ON DELETE CASCADE;

-- A member answers each question once per review, and once outside any review.
DROP INDEX uq_result_feedback_type_order_user;
CREATE UNIQUE INDEX uq_result_feedback_type_order_user
    ON prediction_result_feedback (prediction_result_id, feedback_type, orden, user_id, schema_review_id)
    NULLS NOT DISTINCT WHERE user_id IS NOT NULL;

-- Until now every review of a run showed a reviewer's answers on it, wherever they were given. An
-- answer cannot tell which review it was given in, so it stays in each review of the run its
-- author is assigned to: in the first, and as a copy in each further one. An answer whose author
-- reviews none of the run's reviews stays outside reviews.
UPDATE prediction_result_feedback f
SET schema_review_id = placed.review_id
FROM (
    SELECT f.id AS feedback_id, MIN(rr.schema_review_id) AS review_id
    FROM prediction_result_feedback f
    JOIN prediction_result r ON r.id = f.prediction_result_id
    JOIN schema_review_run rr ON rr.prediction_run_id = r.prediction_run_id
    JOIN schema_review_assignee a ON a.review_id = rr.schema_review_id AND a.user_id = f.user_id
    GROUP BY f.id
) placed
WHERE f.id = placed.feedback_id;

INSERT INTO prediction_result_feedback
    (prediction_result_id, user_id, visitor_id, feedback_type, orden, data_value, created_at, updated_at,
     schema_review_id)
SELECT f.prediction_result_id, f.user_id, f.visitor_id, f.feedback_type, f.orden, f.data_value, f.created_at,
       f.updated_at, rr.schema_review_id
FROM prediction_result_feedback f
JOIN prediction_result r ON r.id = f.prediction_result_id
JOIN schema_review_run rr ON rr.prediction_run_id = r.prediction_run_id
JOIN schema_review_assignee a ON a.review_id = rr.schema_review_id AND a.user_id = f.user_id
WHERE f.schema_review_id IS NOT NULL AND rr.schema_review_id <> f.schema_review_id;

CREATE INDEX idx_result_feedback_review ON prediction_result_feedback (schema_review_id);

-- Every change of an answer, kept when the answer changes again or is removed: who gave it, what
-- it said and who changed it. The history of an answer goes only with its result or its review.
CREATE TABLE prediction_result_feedback_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id BIGINT NOT NULL,
    prediction_result_id BIGINT NOT NULL
        CONSTRAINT fk_feedback_revision_result REFERENCES prediction_result (id) ON DELETE CASCADE,
    schema_review_id BIGINT
        CONSTRAINT fk_feedback_revision_review REFERENCES schema_review (id) ON DELETE CASCADE,
    user_id BIGINT CONSTRAINT fk_feedback_revision_user REFERENCES app_user (id) ON DELETE SET NULL,
    visitor_id UUID CONSTRAINT fk_feedback_revision_visitor REFERENCES visitor (id),
    feedback_type VARCHAR(32) NOT NULL,
    orden INTEGER NOT NULL,
    data_value JSONB,
    change VARCHAR(16) NOT NULL CONSTRAINT ck_feedback_revision_change
        CHECK (change IN ('CREATED', 'UPDATED', 'DELETED')),
    changed_by_user_id BIGINT
        CONSTRAINT fk_feedback_revision_changed_by REFERENCES app_user (id) ON DELETE SET NULL,
    changed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_feedback_revision_value CHECK ((change = 'DELETED') = (data_value IS NULL))
);
CREATE INDEX idx_feedback_revision_result ON prediction_result_feedback_revision (prediction_result_id, id);

-- The answers kept so far start their history as they are now.
INSERT INTO prediction_result_feedback_revision
    (feedback_id, prediction_result_id, schema_review_id, user_id, visitor_id, feedback_type, orden, data_value,
     change, changed_by_user_id, changed_at)
SELECT id, prediction_result_id, schema_review_id, user_id, visitor_id, feedback_type, orden, data_value,
       'CREATED', user_id, updated_at
FROM prediction_result_feedback;
