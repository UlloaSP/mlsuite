-- Feedback on a result is given by a member or by a visitor, never by both. An answer given in a
-- review belongs to that review, so removing a reviewer's response to one review leaves their
-- answers in other reviews and on the public page as they were; answers given elsewhere (a public
-- page) belong to no review. A member answers each question once per review, and once outside any
-- review; a visitor answers once.
CREATE TABLE prediction_result_feedback (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_result_id BIGINT NOT NULL CONSTRAINT fk_result_feedback_result REFERENCES prediction_result,
    user_id BIGINT CONSTRAINT fk_result_feedback_user REFERENCES app_user,
    visitor_id UUID CONSTRAINT fk_result_feedback_visitor REFERENCES visitor (id),
    schema_review_id BIGINT CONSTRAINT fk_result_feedback_review REFERENCES schema_review (id) ON DELETE CASCADE,
    feedback_type VARCHAR(32) NOT NULL CHECK (feedback_type IN ('OUTPUT', 'EXPLANATION')),
    orden INTEGER NOT NULL, data_value JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_result_feedback_author CHECK ((user_id IS NULL) <> (visitor_id IS NULL)));

CREATE UNIQUE INDEX uq_result_feedback_type_order_user
    ON prediction_result_feedback (prediction_result_id, feedback_type, orden, user_id, schema_review_id)
    NULLS NOT DISTINCT WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uq_result_feedback_type_order_visitor
    ON prediction_result_feedback (prediction_result_id, feedback_type, orden, visitor_id)
    WHERE visitor_id IS NOT NULL;
CREATE INDEX idx_result_feedback_review ON prediction_result_feedback (schema_review_id);

-- Every change of an answer, kept when the answer changes again or is removed: who gave it, what
