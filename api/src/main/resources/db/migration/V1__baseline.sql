    updated_by_user_id BIGINT CONSTRAINT fk_organization_updated_by REFERENCES app_user,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, CONSTRAINT uq_organization_slug UNIQUE (slug));

