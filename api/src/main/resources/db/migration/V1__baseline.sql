-- Accounts, and the organizations that own everything else.

CREATE TABLE app_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL, email VARCHAR(100) NOT NULL, full_name VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL, avatar_url TEXT, enabled BOOLEAN NOT NULL,
