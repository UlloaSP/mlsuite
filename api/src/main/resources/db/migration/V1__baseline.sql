-- A model's row is written once its artifact is in object storage, the artifact's only home, and
-- verified: the row names the exact object version and the artifact's SHA-256. A model runs once
-- its environment is built and the model has loaded there (READY); until then it is PREPARING,
-- claimed by one API instance at a time under a lease, or FAILED with the reason.
CREATE TABLE model (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    organization_id BIGINT NOT NULL CONSTRAINT fk_model_organization REFERENCES organization,
    user_id BIGINT NOT NULL CONSTRAINT fk_model_user
        REFERENCES app_user (id) ON DELETE CASCADE ON UPDATE CASCADE DEFERRABLE,
    updated_by_user_id BIGINT CONSTRAINT fk_model_updated_by REFERENCES app_user,
    name VARCHAR(100) NOT NULL, type VARCHAR(255) NOT NULL, specific_type VARCHAR(255) NOT NULL,
    file_name VARCHAR(255) NOT NULL, storage_bucket VARCHAR(100) NOT NULL, storage_object_key VARCHAR(512) NOT NULL,
    storage_version_id VARCHAR(255) NOT NULL, storage_etag VARCHAR(128) NOT NULL, model_size_bytes BIGINT NOT NULL,
    artifact_sha256 VARCHAR(64) NOT NULL CONSTRAINT ck_model_artifact_sha256 CHECK (artifact_sha256 ~ '^[0-9a-f]{64}$'),
    artifact_verified_at TIMESTAMPTZ NOT NULL,
    -- What the model's bundle says about it: its manifest as uploaded, and the feature importances
    -- the runtime reads from its structure (absent for models without one).
    input_schema JSONB NOT NULL, bundle_manifest JSONB NOT NULL DEFAULT '{}'::jsonb, feature_importances JSONB,
    environment_key VARCHAR(64) NOT NULL REFERENCES runtime_environment (environment_key),
    runtime_state VARCHAR(16) NOT NULL CHECK (runtime_state IN ('PREPARING', 'READY', 'FAILED')),
    runtime_error VARCHAR(2000), runtime_attempts INTEGER NOT NULL DEFAULT 0,
    runtime_lease_owner VARCHAR(128), runtime_lease_expires_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_model_name_org UNIQUE (name, organization_id));

CREATE INDEX idx_model_runtime_preparing ON model (id) WHERE runtime_state = 'PREPARING';
CREATE INDEX idx_model_environment ON model (environment_key);

CREATE TABLE plugin_metadata (id VARCHAR(64) PRIMARY KEY,
    organization_id BIGINT NOT NULL CONSTRAINT fk_plugin_metadata_org REFERENCES organization,
    plugin_type VARCHAR(32) NOT NULL, kind VARCHAR(180), file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL, object_key VARCHAR(512) NOT NULL, size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) CONSTRAINT ck_plugin_metadata_sha256 CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
    storage_version_id VARCHAR(255), updated_by_user_id BIGINT CONSTRAINT fk_plugin_metadata_updated_by REFERENCES app_user,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL);

CREATE INDEX idx_plugin_catalog ON plugin_metadata (organization_id, updated_at DESC, id);

-- Schemas: versioned form and output contracts, the models each version binds, the bookmarks that
-- pin a version, and the drafts being edited.

CREATE TABLE schema_artifact (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL CONSTRAINT fk_schema_artifact_org REFERENCES organization,
    name VARCHAR(180) NOT NULL, description VARCHAR(800),
    created_by BIGINT CONSTRAINT fk_schema_artifact_created_by REFERENCES app_user,
    updated_by BIGINT CONSTRAINT fk_schema_artifact_updated_by REFERENCES app_user,
    archived_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_artifact_org_name UNIQUE (organization_id, name));

CREATE TABLE schema_version (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_id BIGINT NOT NULL CONSTRAINT fk_schema_version_schema REFERENCES schema_artifact,
    version_number INTEGER NOT NULL, name VARCHAR(180), form_schema_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL, CONSTRAINT uq_schema_version_schema_version UNIQUE (schema_id, version_number));

-- A bookmark describes itself: in its schema's repository and on its public page. It is private
-- until a member publishes it; public_id is assigned on the first publish or when an API client
-- is given the bookmark, and kept afterwards, so a shared /explore link survives unpublishing. A
-- published bookmark may carry a note for its visitors: the paper it was published in, a DOI,
-- terms of use. Free text, shown on the public page below the description.
CREATE TABLE schema_bookmark (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_id BIGINT NOT NULL CONSTRAINT fk_schema_bookmark_schema REFERENCES schema_artifact,
    schema_version_id BIGINT NOT NULL CONSTRAINT fk_schema_bookmark_version REFERENCES schema_version,
    name VARCHAR(180) NOT NULL, description VARCHAR(800), visibility VARCHAR(16) NOT NULL DEFAULT 'PRIVATE'
        CONSTRAINT ck_schema_bookmark_visibility CHECK (visibility IN ('PRIVATE', 'PUBLIC')),
    public_id VARCHAR(36), publication_note VARCHAR(1000), created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_schema_bookmark_public_has_id CHECK (visibility = 'PRIVATE' OR public_id IS NOT NULL),
    CONSTRAINT uq_schema_bookmark_public_id UNIQUE (public_id),
    CONSTRAINT uq_schema_bookmark_schema_name UNIQUE (schema_id, name));

CREATE TABLE schema_draft (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_id BIGINT NOT NULL CONSTRAINT fk_schema_draft_schema REFERENCES schema_artifact,
    base_version_id BIGINT NOT NULL CONSTRAINT fk_schema_draft_base REFERENCES schema_version,
    published_version_id BIGINT CONSTRAINT fk_schema_draft_published REFERENCES schema_version,
    name VARCHAR(180) NOT NULL, status VARCHAR(32) NOT NULL CHECK (status IN ('DRAFT', 'CONFLICT', 'PUBLISHED')),
    revision BIGINT, form_schema_json JSONB NOT NULL, bindings_json JSONB NOT NULL, base_bindings_json JSONB,
    updated_by BIGINT CONSTRAINT fk_schema_draft_updated_by REFERENCES app_user,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL);

CREATE TABLE schema_model_binding (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_version_id BIGINT NOT NULL CONSTRAINT fk_schema_binding_version REFERENCES schema_version,
    model_id BIGINT NOT NULL CONSTRAINT fk_schema_binding_model REFERENCES model,
    plugin_policy_json JSONB, created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_binding_model UNIQUE (schema_version_id, model_id));

-- A visitor is whoever runs a public bookmark without an account: a random id the API issues in a
-- browser cookie on their first run. A visitor's runs and feedback are kept for good and told
-- apart from the workspace's own by the run's origin.
CREATE TABLE visitor (id UUID PRIMARY KEY, created_at TIMESTAMPTZ NOT NULL, last_seen_at TIMESTAMPTZ NOT NULL);

-- Predictions. origin says where a run was made: the workspace form, a bookmark's public page, or
-- an API client. A public run by a visitor names them; one by a signed-in account names the
-- account as a workspace run does.
CREATE TABLE prediction_run (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_version_id BIGINT NOT NULL CONSTRAINT fk_prediction_run_version REFERENCES schema_version,
    schema_bookmark_id BIGINT CONSTRAINT fk_prediction_run_bookmark REFERENCES schema_bookmark,
    name VARCHAR(255) NOT NULL, input_data_json JSONB NOT NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN ('SUCCESS', 'PARTIAL_SUCCESS', 'FAILED')),
    origin VARCHAR(16) NOT NULL CONSTRAINT ck_prediction_run_origin CHECK (origin IN ('WORKSPACE', 'PUBLIC', 'API')),
    visitor_id UUID CONSTRAINT fk_prediction_run_visitor REFERENCES visitor (id),
    created_by_email VARCHAR(255), created_by_name VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_prediction_run_version_name UNIQUE (schema_version_id, name));

-- The inference catalog filters runs by bookmark and pages them by creation time, newest first and
-- then by id; a model's results are looked up when it is deleted or archived.
CREATE INDEX ix_prediction_run_visitor_bookmark ON prediction_run (visitor_id, schema_bookmark_id) WHERE visitor_id IS NOT NULL;
CREATE INDEX idx_prediction_run_bookmark ON prediction_run (schema_bookmark_id);
CREATE INDEX idx_prediction_run_created ON prediction_run (created_at DESC, id);

-- environment_key is the environment that computed the result.
CREATE TABLE prediction_result (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_run_id BIGINT NOT NULL CONSTRAINT fk_prediction_result_run REFERENCES prediction_run,
    model_id BIGINT NOT NULL CONSTRAINT fk_prediction_result_model REFERENCES model,
    environment_key VARCHAR(64) REFERENCES runtime_environment (environment_key),
    status VARCHAR(32) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED')),
    error_message TEXT, error_json JSONB, model_input_json JSONB NOT NULL, output_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL, CONSTRAINT uq_prediction_result_run_model UNIQUE (prediction_run_id, model_id));

CREATE INDEX idx_prediction_result_model ON prediction_result (model_id);

-- A prediction run a member explicitly marked as a public example of a bookmark. The run stays the
