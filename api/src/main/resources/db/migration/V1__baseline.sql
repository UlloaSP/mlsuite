CREATE INDEX idx_feedback_revision_result ON prediction_result_feedback_revision (prediction_result_id, id);

-- A bulk upload runs on the server as a job, so it survives the browser tab that started it. The
-- client uploads its rows once; API workers claim a job with SELECT ... FOR UPDATE SKIP LOCKED and
-- hold it under a lease, so a crashed or restarted worker's job is claimed again once its lease
-- expires. Each row ends as a stored run (DONE) or with the reason it could not (FAILED).
CREATE TABLE prediction_job (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    schema_bookmark_id BIGINT NOT NULL REFERENCES schema_bookmark (id) ON DELETE CASCADE,
    schema_version_id BIGINT NOT NULL REFERENCES schema_version (id) ON DELETE CASCADE,
    created_by_user_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'CANCELLED')),
    total_rows INTEGER NOT NULL, done_rows INTEGER NOT NULL DEFAULT 0, failed_rows INTEGER NOT NULL DEFAULT 0,
    lease_owner VARCHAR(128), lease_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, finished_at TIMESTAMPTZ);

CREATE INDEX idx_prediction_job_open ON prediction_job (id) WHERE status IN ('QUEUED', 'RUNNING');
CREATE INDEX idx_prediction_job_bookmark ON prediction_job (schema_bookmark_id, id DESC);

CREATE TABLE prediction_job_row (
    job_id BIGINT NOT NULL REFERENCES prediction_job (id) ON DELETE CASCADE,
    row_index INTEGER NOT NULL, name VARCHAR(255) NOT NULL, input_data JSONB NOT NULL, model_inputs JSONB NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'DONE', 'FAILED')),
    prediction_run_id BIGINT REFERENCES prediction_run (id) ON DELETE SET NULL, error TEXT, PRIMARY KEY (job_id, row_index));

CREATE INDEX idx_prediction_job_row_pending ON prediction_job_row (job_id, row_index) WHERE status = 'PENDING';

-- The inferences table's columns and sorts are derived from stored runs (inputs, reports, answers).
-- What a run shows does not depend on the locale, only how it is written and compared does, so
-- each run's projection is kept once, by a background refresh, and every locale formats and
-- collates it when it reads it. One row per run: the raw value of each of its data columns, its
-- feedback status, and a digest of its columns' ids and groups (runs sharing one have the same
-- columns), as projection_version projects them with its snapshot's models named as models_stamp
-- says. Every change of the run's answers adds one to answer_changes, in the same transaction (a
-- row may exist for that alone, before it is projected); the projection is current while
-- projected_changes still equals it. A migration that changes answers or what a row is projected
-- from must empty this table.
CREATE TABLE inference_row (
    prediction_run_id BIGINT PRIMARY KEY REFERENCES prediction_run (id) ON DELETE CASCADE,
    answer_changes BIGINT NOT NULL DEFAULT 0, projected_changes BIGINT, projection_version INTEGER,
    schema_version_id BIGINT, models_stamp TEXT, layout TEXT, feedback_status VARCHAR(32), cell_values JSONB,
    CONSTRAINT ck_inference_row_projected CHECK (num_nulls(projected_changes, projection_version, schema_version_id,
        models_stamp, layout, feedback_status, cell_values) IN (0, 7)));

-- Outside software runs an organization's models as one of its API clients. A client holds any
-- number of keys, so a key can be replaced without stopping its software, and may run the
-- bookmarks it was given access to, public or not. Every call a key makes is kept in api_request:
-- it meters the client, feeds the organization's and the platform's views, and ties a call to the
-- run it made. A client is suspended only by the platform, with the reason its organization is
-- shown.
CREATE TABLE api_client (id BIGSERIAL PRIMARY KEY,
    organization_id BIGINT NOT NULL CONSTRAINT fk_api_client_organization REFERENCES organization (id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL, description VARCHAR(400),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CONSTRAINT ck_api_client_status CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    suspension_reason VARCHAR(400), suspended_at TIMESTAMPTZ, created_by_name VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_api_client_suspension CHECK ((status = 'SUSPENDED') = (suspended_at IS NOT NULL)));

CREATE UNIQUE INDEX uq_api_client_organization_name ON api_client (organization_id, lower(name));

-- Only the secret's SHA-256 is kept, with its first characters to tell keys apart.
CREATE TABLE api_client_key (id BIGSERIAL PRIMARY KEY,
    api_client_id BIGINT NOT NULL CONSTRAINT fk_api_client_key_client REFERENCES api_client (id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL, key_prefix VARCHAR(16) NOT NULL, key_hash CHAR(64) NOT NULL,
    created_by_name VARCHAR(255), created_at TIMESTAMPTZ NOT NULL, last_used_at TIMESTAMPTZ,
    CONSTRAINT uq_api_client_key_hash UNIQUE (key_hash));

CREATE INDEX ix_api_client_key_client ON api_client_key (api_client_id);

CREATE TABLE api_client_bookmark (
    api_client_id BIGINT NOT NULL CONSTRAINT fk_api_client_bookmark_client REFERENCES api_client (id) ON DELETE CASCADE,
    schema_bookmark_id BIGINT NOT NULL
        CONSTRAINT fk_api_client_bookmark_bookmark REFERENCES schema_bookmark (id) ON DELETE CASCADE,
    PRIMARY KEY (api_client_id, schema_bookmark_id));

CREATE INDEX ix_api_client_bookmark_bookmark ON api_client_bookmark (schema_bookmark_id);

-- One call made with a valid key, whatever its outcome. The names are snapshots, so a call still
-- reads after its client, key or bookmark is gone; the organization's month is counted here, so
-- deleting a client does not give its calls back.
CREATE TABLE api_request (id BIGSERIAL PRIMARY KEY, request_id UUID NOT NULL CONSTRAINT uq_api_request_request_id UNIQUE,
    organization_id BIGINT NOT NULL CONSTRAINT fk_api_request_organization REFERENCES organization (id) ON DELETE CASCADE,
    api_client_id BIGINT CONSTRAINT fk_api_request_client REFERENCES api_client (id) ON DELETE SET NULL,
    client_name VARCHAR(80) NOT NULL,
    api_client_key_id BIGINT CONSTRAINT fk_api_request_key REFERENCES api_client_key (id) ON DELETE SET NULL,
    key_prefix VARCHAR(16) NOT NULL,
    schema_bookmark_id BIGINT CONSTRAINT fk_api_request_bookmark REFERENCES schema_bookmark (id) ON DELETE SET NULL,
    bookmark_name VARCHAR(180),
    prediction_run_id BIGINT CONSTRAINT fk_api_request_run REFERENCES prediction_run (id) ON DELETE SET NULL,
    status INTEGER NOT NULL, error_code VARCHAR(40), duration_ms INTEGER NOT NULL, created_at TIMESTAMPTZ NOT NULL);

CREATE INDEX ix_api_request_organization_created ON api_request (organization_id, created_at DESC);
CREATE INDEX ix_api_request_client_created ON api_request (api_client_id, created_at DESC);
CREATE INDEX ix_api_request_created ON api_request (created_at);

