-- Predictions: runs, their results, the public examples of a bookmark, the inference table's
-- projection, and bulk jobs.

-- origin says where a run was made: the workspace form, a bookmark's public page, or an API
-- client. Its author is the member, the visitor or the client who made it. A run carries its
-- snapshot's schema, so the bookmark it was reached through is one of that schema; the bookmark is
-- only how it was reached, so a run outlives it. A run is written once and never changed.
CREATE TABLE prediction_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_prediction_run PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    schema_id BIGINT NOT NULL,
    schema_version_id BIGINT NOT NULL,
    schema_bookmark_id BIGINT,
    name VARCHAR(255) NOT NULL CONSTRAINT ck_prediction_run_name_present CHECK (btrim(name) <> ''),
    input_data JSONB NOT NULL,
    status VARCHAR(32) NOT NULL CONSTRAINT ck_prediction_run_status CHECK (status IN ('SUCCESS', 'PARTIAL_SUCCESS', 'FAILED')),
    origin VARCHAR(16) NOT NULL CONSTRAINT ck_prediction_run_origin CHECK (origin IN ('WORKSPACE', 'PUBLIC', 'API')),
    created_by_principal_id BIGINT NOT NULL,
    -- The author's kind, which the origin agrees with: an API run is a client's and only a client's,
    -- and a visitor runs only on a public page.
    created_by_kind VARCHAR(16) NOT NULL,
    -- The client an API run was made with, while it exists (its key is V6's): of the run's organization.
    api_client_id BIGINT CONSTRAINT ck_prediction_run_api_client CHECK (api_client_id IS NULL OR origin = 'API'),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_prediction_run_created_by FOREIGN KEY (created_by_principal_id, created_by_kind)
        REFERENCES principal (id, kind),
    CONSTRAINT ck_prediction_run_origin_author CHECK ((origin = 'API') = (created_by_kind = 'API_CLIENT')
        AND (created_by_kind <> 'VISITOR' OR origin = 'PUBLIC')),
    CONSTRAINT uq_prediction_run_schema_id UNIQUE (schema_id, id),
    CONSTRAINT uq_prediction_run_version_id UNIQUE (schema_version_id, id),
    CONSTRAINT fk_prediction_run_schema FOREIGN KEY (organization_id, schema_id) REFERENCES schema (organization_id, id),
    CONSTRAINT fk_prediction_run_version FOREIGN KEY (schema_id, schema_version_id) REFERENCES schema_version (schema_id, id),
    CONSTRAINT fk_prediction_run_bookmark FOREIGN KEY (schema_id, schema_bookmark_id)
        REFERENCES schema_bookmark (schema_id, id) ON DELETE SET NULL (schema_bookmark_id));

-- A run's name is unique on its snapshot, whatever its case.
CREATE UNIQUE INDEX uq_prediction_run_version_name ON prediction_run (schema_version_id, lower(name));

-- A run is a record: once written only the bookmark it came from may go (with the bookmark).
CREATE TRIGGER trg_prediction_run_fixed BEFORE UPDATE OF id, organization_id, schema_id, schema_version_id, name, input_data, status,
    origin, created_by_principal_id, created_by_kind, created_at ON prediction_run FOR EACH ROW
    WHEN ((OLD.id, OLD.organization_id, OLD.schema_id, OLD.schema_version_id, OLD.name, OLD.input_data, OLD.status, OLD.origin,
        OLD.created_by_principal_id, OLD.created_by_kind, OLD.created_at)
        IS DISTINCT FROM (NEW.id, NEW.organization_id, NEW.schema_id, NEW.schema_version_id, NEW.name, NEW.input_data, NEW.status, NEW.origin,
        NEW.created_by_principal_id, NEW.created_by_kind, NEW.created_at))
    EXECUTE FUNCTION refuse_change('ck_prediction_run_fixed');

-- The inference catalog filters runs by bookmark and pages them by creation time, newest first and
-- then by id; a public page reads back its author's runs of its bookmark.
CREATE INDEX idx_prediction_run_bookmark ON prediction_run (schema_bookmark_id);
CREATE INDEX idx_prediction_run_created ON prediction_run (organization_id, created_at DESC, id);
CREATE INDEX idx_prediction_run_schema_created ON prediction_run (schema_id, created_at DESC);
CREATE INDEX idx_prediction_run_author_bookmark ON prediction_run (created_by_principal_id, schema_bookmark_id);
CREATE INDEX idx_search_run_name_trgm ON prediction_run USING GIN (lower(name) gin_trgm_ops);

-- A result carries its run's snapshot, so its model is one that snapshot binds. environment_key is
-- the environment that computed it.
CREATE TABLE prediction_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_prediction_result PRIMARY KEY,
    schema_version_id BIGINT NOT NULL,
    prediction_run_id BIGINT NOT NULL,
    model_id BIGINT NOT NULL,
    environment_key VARCHAR(64) NOT NULL CONSTRAINT fk_prediction_result_environment
        REFERENCES runtime_environment (environment_key),
    status VARCHAR(32) NOT NULL CONSTRAINT ck_prediction_result_status CHECK (status IN ('SUCCESS', 'FAILED')),
    error_message TEXT,
    error_detail JSONB,
    -- A failed result says why, as text and as the runtime's answer; a successful one does not.
    CONSTRAINT ck_prediction_result_failed CHECK ((status = 'FAILED') = (error_message IS NOT NULL)),
    CONSTRAINT ck_prediction_result_error CHECK ((error_message IS NULL) = (error_detail IS NULL)),
    model_input JSONB NOT NULL,
    -- What the model answered; a failed result answered nothing but its error.
    output JSONB,
    CONSTRAINT ck_prediction_result_output CHECK ((status = 'SUCCESS') = (output IS NOT NULL)),
    -- The seal a workspace result was saved from: one execution is saved in one run.
    attestation_sha256 VARCHAR(64) CONSTRAINT uq_prediction_result_attestation UNIQUE
        CONSTRAINT ck_prediction_result_attestation CHECK (attestation_sha256 ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_prediction_result_run_model UNIQUE (prediction_run_id, model_id),
    CONSTRAINT uq_prediction_result_run_id UNIQUE (prediction_run_id, id),
    CONSTRAINT fk_prediction_result_run FOREIGN KEY (schema_version_id, prediction_run_id)
        REFERENCES prediction_run (schema_version_id, id),
    CONSTRAINT fk_prediction_result_binding FOREIGN KEY (schema_version_id, model_id)
        REFERENCES schema_model_binding (schema_version_id, model_id));

CREATE INDEX idx_prediction_result_model ON prediction_result (model_id);
CREATE INDEX idx_prediction_result_binding ON prediction_result (schema_version_id, model_id);

-- At commit a run has one result for every model its snapshot binds, and its status says how they
-- went: all succeeded, all failed, or some of each. Checked whenever a run or a result is written.
CREATE FUNCTION prediction_run_agrees_with_results() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    run_id BIGINT;
    run_status VARCHAR(32);
    version_id BIGINT;
    results INTEGER;
    succeeded INTEGER;
BEGIN
    IF TG_TABLE_NAME = 'prediction_run' THEN
        run_id := NEW.id;
    ELSE
        run_id := NEW.prediction_run_id;
    END IF;
    SELECT status, schema_version_id INTO run_status, version_id FROM prediction_run WHERE id = run_id;
    IF NOT FOUND THEN
        RETURN NULL; -- removed again in the same transaction
    END IF;
    SELECT count(*), count(*) FILTER (WHERE status = 'SUCCESS') INTO results, succeeded
        FROM prediction_result WHERE prediction_run_id = run_id;
    IF results <> (SELECT count(*) FROM schema_model_binding WHERE schema_version_id = version_id)
        OR run_status <> (CASE WHEN succeeded = results THEN 'SUCCESS' WHEN succeeded = 0 THEN 'FAILED'
            ELSE 'PARTIAL_SUCCESS' END) THEN
        RAISE EXCEPTION 'Run % does not agree with its results: violates check constraint "ck_prediction_run_results"', run_id USING ERRCODE = 'check_violation',
            CONSTRAINT = 'ck_prediction_run_results', TABLE = 'prediction_run';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_prediction_run_results AFTER INSERT ON prediction_run
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION prediction_run_agrees_with_results();
CREATE CONSTRAINT TRIGGER trg_prediction_result_run AFTER INSERT ON prediction_result
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION prediction_run_agrees_with_results();

-- A result goes only with its run (by the commit, the run is gone too), or with a snapshot a purge
-- is destroying, whose runs go in a later step of the same purge.
CREATE FUNCTION prediction_result_goes_with_its_run() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM prediction_run WHERE id = OLD.prediction_run_id)
        AND NOT EXISTS (SELECT 1 FROM purge_job_version WHERE schema_version_id = OLD.schema_version_id) THEN
        RAISE EXCEPTION 'A result is removed only with its run: violates check constraint "ck_prediction_result_with_run"' USING ERRCODE = 'check_violation',
            CONSTRAINT = 'ck_prediction_result_with_run', TABLE = 'prediction_result';
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_prediction_result_with_run AFTER DELETE ON prediction_result
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION prediction_result_goes_with_its_run();

-- A result is what a model computed: it never changes.
CREATE TRIGGER trg_prediction_result_fixed BEFORE UPDATE ON prediction_result FOR EACH ROW
    WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION refuse_change('ck_prediction_result_fixed');

-- A run a member explicitly marked as a public example of a bookmark of its schema. The run stays
-- the source of truth for the inputs: nothing is copied here. An example is served only while the
-- bookmark is public and still pins the snapshot the run executed on, so a moved bookmark needs no
-- cleanup. Rows leave with their run or their bookmark.
CREATE TABLE schema_bookmark_example (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_schema_bookmark_example PRIMARY KEY,
    schema_id BIGINT NOT NULL,
    schema_bookmark_id BIGINT NOT NULL,
    prediction_run_id BIGINT NOT NULL,
    public_id VARCHAR(36) NOT NULL CONSTRAINT uq_schema_bookmark_example_public_id UNIQUE,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_schema_bookmark_example_created_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_schema_bookmark_example_bookmark_run UNIQUE (schema_bookmark_id, prediction_run_id),
    CONSTRAINT fk_schema_bookmark_example_bookmark FOREIGN KEY (schema_id, schema_bookmark_id)
        REFERENCES schema_bookmark (schema_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_schema_bookmark_example_run FOREIGN KEY (schema_id, prediction_run_id)
        REFERENCES prediction_run (schema_id, id) ON DELETE CASCADE);

CREATE INDEX idx_schema_bookmark_example_run ON schema_bookmark_example (prediction_run_id);

-- A rebuildable cache, not a source of truth: the inferences table's columns and sorts are derived
-- from stored runs (inputs, reports, answers), and emptying this table loses nothing.
-- What a run shows does not depend on the locale, only how it is written and compared does, so
-- each run's projection is kept once, by a background refresh, and every locale formats and
-- collates it when it reads it. One row per run: the raw value of each of its data columns, its
-- feedback status, and a digest of its snapshot and of its columns' ids and groups (runs sharing
-- one have the same columns), as projection_version projects them with its snapshot's models named
-- as models_stamp says. The row holds nothing it is not the only home of: the run's snapshot is
-- read from the run. A trigger on the answers adds one to answer_changes in the transaction that
-- changes them (a row may exist for that alone, before it is projected); the projection is current while
-- projected_changes still equals it. A migration that changes answers or what a row is projected
-- from must empty this table.
CREATE TABLE prediction_run_projection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_prediction_run_projection PRIMARY KEY,
    prediction_run_id BIGINT NOT NULL CONSTRAINT uq_prediction_run_projection_run UNIQUE
        CONSTRAINT fk_prediction_run_projection_run REFERENCES prediction_run (id) ON DELETE CASCADE,
    answer_changes BIGINT NOT NULL DEFAULT 0,
    projected_changes BIGINT,
    projection_version INTEGER,
    models_stamp TEXT,
    layout_sha256 VARCHAR(64) CONSTRAINT ck_prediction_run_projection_layout CHECK (layout_sha256 ~ '^[0-9a-f]{64}$'),
    feedback_status VARCHAR(32) CONSTRAINT ck_prediction_run_projection_feedback_status
        CHECK (feedback_status IN ('COMPLETED', 'PENDING', 'NOT_REQUIRED', 'ERROR')),
    cell_values JSONB,
    -- A row is either only counting answer changes, or projected in full.
    CONSTRAINT ck_prediction_run_projection_projected CHECK (num_nulls(projected_changes, projection_version, models_stamp, layout_sha256,
        feedback_status, cell_values) IN (0, 6)));

-- A bulk upload runs on the server as a job, so it survives the browser tab that started it. The
-- client uploads its rows once; API workers claim a job with SELECT ... FOR UPDATE SKIP LOCKED and
-- hold it under a lease, so a crashed or restarted worker's job is claimed again once its lease
-- expires. Each row ends as a stored run (DONE) or with the reason it could not (FAILED). A job runs
-- a bookmark on the snapshot it pinned when the job started, so both are of one schema, the job's
-- organization's; the job carries that schema. A job is work in flight: it leaves with its bookmark
-- or its snapshot.
CREATE TABLE prediction_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_prediction_job PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    schema_id BIGINT NOT NULL,
    -- The bookmark it runs; a finished job outlives its bookmark, an open one keeps it.
    schema_bookmark_id BIGINT,
    schema_version_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL CONSTRAINT ck_prediction_job_status CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'CANCELLED')),
    total_rows INTEGER NOT NULL CONSTRAINT ck_prediction_job_total CHECK (total_rows >= 1),
    done_rows INTEGER NOT NULL DEFAULT 0,
    failed_rows INTEGER NOT NULL DEFAULT 0,
    lease_owner VARCHAR(128),
    lease_expires_at TIMESTAMPTZ,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_prediction_job_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_prediction_job_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    -- Why the system stopped it before its rows ran (its pending rows failed with this reason).
    stop_reason TEXT CONSTRAINT ck_prediction_job_stop_reason CHECK (stop_reason IS NULL OR status = 'COMPLETED'),
    -- A running job is leased, and only a running one; a lease has an owner and an expiry together.
    CONSTRAINT ck_prediction_job_lease CHECK ((lease_owner IS NULL) = (lease_expires_at IS NULL)
        AND (status = 'RUNNING') = (lease_owner IS NOT NULL)),
    CONSTRAINT ck_prediction_job_completed CHECK (status <> 'COMPLETED' OR done_rows + failed_rows = total_rows),
    CONSTRAINT ck_prediction_job_finished CHECK ((finished_at IS NOT NULL) = (status IN ('COMPLETED', 'CANCELLED'))),
    CONSTRAINT ck_prediction_job_rows CHECK (done_rows >= 0 AND failed_rows >= 0 AND done_rows + failed_rows <= total_rows),
    CONSTRAINT uq_prediction_job_id_version UNIQUE (id, schema_version_id),
    CONSTRAINT fk_prediction_job_schema FOREIGN KEY (organization_id, schema_id) REFERENCES schema (organization_id, id),
    CONSTRAINT fk_prediction_job_bookmark FOREIGN KEY (schema_id, schema_bookmark_id)
        REFERENCES schema_bookmark (schema_id, id) ON DELETE SET NULL (schema_bookmark_id),
    CONSTRAINT ck_prediction_job_open_bookmark CHECK (status IN ('COMPLETED', 'CANCELLED') OR schema_bookmark_id IS NOT NULL),
    CONSTRAINT fk_prediction_job_version FOREIGN KEY (schema_id, schema_version_id)
        REFERENCES schema_version (schema_id, id) ON DELETE CASCADE);

CREATE INDEX idx_prediction_job_open ON prediction_job (id) WHERE status IN ('QUEUED', 'RUNNING');
CREATE INDEX idx_prediction_job_bookmark ON prediction_job (schema_bookmark_id, id DESC);
CREATE INDEX idx_prediction_job_version ON prediction_job (schema_version_id);
CREATE INDEX idx_prediction_job_created_by ON prediction_job (created_by_principal_id);
CREATE INDEX idx_prediction_job_organization ON prediction_job (organization_id, schema_id);

-- A row's run is one of its job's snapshot: the row carries the job's snapshot.
CREATE TABLE prediction_job_row (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_prediction_job_row PRIMARY KEY,
    prediction_job_id BIGINT NOT NULL,
    schema_version_id BIGINT NOT NULL,
    row_index INTEGER NOT NULL CONSTRAINT ck_prediction_job_row_index CHECK (row_index >= 0),
    name VARCHAR(255) NOT NULL CONSTRAINT ck_prediction_job_row_name_present CHECK (btrim(name) <> ''),
    -- What the row sends, kept until it is a run: a done row's inputs are its run's.
    input_data JSONB,
    model_inputs JSONB,
    status VARCHAR(16) NOT NULL CONSTRAINT ck_prediction_job_row_status CHECK (status IN ('PENDING', 'DONE', 'FAILED')),
    prediction_run_id BIGINT,
    error_message TEXT,
    CONSTRAINT uq_prediction_job_row UNIQUE (prediction_job_id, row_index),
    CONSTRAINT fk_prediction_job_row_job FOREIGN KEY (prediction_job_id, schema_version_id)
        REFERENCES prediction_job (id, schema_version_id) ON DELETE CASCADE,
    CONSTRAINT fk_prediction_job_row_run FOREIGN KEY (schema_version_id, prediction_run_id)
        REFERENCES prediction_run (schema_version_id, id) ON DELETE SET NULL (prediction_run_id),
    CONSTRAINT ck_prediction_job_row_error CHECK ((status = 'FAILED') = (error_message IS NOT NULL)),
    CONSTRAINT ck_prediction_job_row_run CHECK (prediction_run_id IS NULL OR status = 'DONE'),
    CONSTRAINT ck_prediction_job_row_payload CHECK ((status = 'DONE') = (input_data IS NULL)
        AND (input_data IS NULL) = (model_inputs IS NULL)));

CREATE INDEX idx_prediction_job_row_pending ON prediction_job_row (prediction_job_id, row_index) WHERE status = 'PENDING';
-- A run is the outcome of at most one row.
CREATE UNIQUE INDEX uq_prediction_job_row_run ON prediction_job_row (prediction_run_id) WHERE prediction_run_id IS NOT NULL;

CREATE TRIGGER trg_prediction_run_not_purging BEFORE INSERT ON prediction_run FOR EACH ROW
    EXECUTE FUNCTION refuse_under_purge('schema', 'schema_id');
CREATE TRIGGER trg_prediction_job_not_purging BEFORE INSERT ON prediction_job FOR EACH ROW
    EXECUTE FUNCTION refuse_under_purge('schema', 'schema_id');
