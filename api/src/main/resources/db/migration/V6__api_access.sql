-- Outside software runs an organization's models as one of its API clients. A client holds any
-- number of keys, so a key can be replaced without stopping its software, and may run the
-- bookmarks it was given access to, public or not. Every call a key makes is kept in api_request:
-- it meters the client, feeds the organization's and the platform's views, and ties a call to the
-- run it made. A client is suspended only by the platform, with the reason its organization is
-- shown. A client is a principal: the runs it makes name it as their author.
CREATE TABLE api_client (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_api_client PRIMARY KEY,
    organization_id BIGINT NOT NULL CONSTRAINT fk_api_client_organization REFERENCES organization (id),
    name VARCHAR(80) NOT NULL CONSTRAINT ck_api_client_name_present CHECK (btrim(name) <> ''),
    description VARCHAR(400),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CONSTRAINT ck_api_client_status CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    suspension_reason VARCHAR(400),
    suspended_at TIMESTAMPTZ,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_api_client_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_api_client_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_api_client_suspension CHECK ((status = 'SUSPENDED') = (suspended_at IS NOT NULL)),
    CONSTRAINT ck_api_client_suspension_reason CHECK (status = 'SUSPENDED' OR suspension_reason IS NULL),
    CONSTRAINT uq_api_client_org_id UNIQUE (organization_id, id));

CREATE UNIQUE INDEX uq_api_client_organization_name ON api_client (organization_id, lower(name));

ALTER TABLE principal ADD CONSTRAINT fk_principal_api_client
    FOREIGN KEY (api_client_id) REFERENCES api_client (id) ON DELETE SET NULL;

CREATE FUNCTION api_client_is_a_principal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO principal (kind, api_client_id) VALUES ('API_CLIENT', NEW.id);
    RETURN NEW;
END $$;
CREATE TRIGGER trg_api_client_principal AFTER INSERT ON api_client FOR EACH ROW EXECUTE FUNCTION api_client_is_a_principal();

CREATE FUNCTION api_client_leaves_its_principal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE principal SET former_label = OLD.name WHERE api_client_id = OLD.id;
    RETURN OLD;
END $$;
CREATE TRIGGER trg_api_client_principal_label BEFORE DELETE ON api_client FOR EACH ROW EXECUTE FUNCTION api_client_leaves_its_principal();

-- Only the secret's SHA-256 is kept, with its first characters to tell keys apart. Revoking a key
-- deletes it.
CREATE TABLE api_client_key (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_api_client_key PRIMARY KEY,
    api_client_id BIGINT NOT NULL CONSTRAINT fk_api_client_key_client REFERENCES api_client (id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL CONSTRAINT ck_api_client_key_name_present CHECK (btrim(name) <> ''),
    key_prefix VARCHAR(16) NOT NULL,
    key_hash VARCHAR(64) NOT NULL CONSTRAINT uq_api_client_key_hash UNIQUE
        CONSTRAINT ck_api_client_key_hash CHECK (key_hash ~ '^[0-9a-f]{64}$'),
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_api_client_key_created_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ);

CREATE INDEX idx_api_client_key_client ON api_client_key (api_client_id);

-- A bookmark a client may run, granted by a member. A client runs only its own organization's
-- bookmarks: the row carries the client's organization and the bookmark's schema, which must be
-- that organization's.
CREATE TABLE api_client_bookmark (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_api_client_bookmark PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    schema_id BIGINT NOT NULL,
    api_client_id BIGINT NOT NULL,
    schema_bookmark_id BIGINT NOT NULL,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_api_client_bookmark_created_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_api_client_bookmark UNIQUE (api_client_id, schema_bookmark_id),
    CONSTRAINT fk_api_client_bookmark_client FOREIGN KEY (organization_id, api_client_id)
        REFERENCES api_client (organization_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_api_client_bookmark_schema FOREIGN KEY (organization_id, schema_id)
        REFERENCES schema (organization_id, id),
    CONSTRAINT fk_api_client_bookmark_bookmark FOREIGN KEY (schema_id, schema_bookmark_id)
        REFERENCES schema_bookmark (schema_id, id) ON DELETE CASCADE);

CREATE INDEX idx_api_client_bookmark_bookmark ON api_client_bookmark (schema_bookmark_id);
CREATE INDEX idx_api_client_bookmark_schema ON api_client_bookmark (organization_id, schema_id);

-- One call made with a valid key, whatever its outcome: an append-only log. Like the audit log it
-- outlives what it names, so the client, key, bookmark and run are plain ids beside the names they
-- had; the organization's month is counted here, so deleting a client does not give its calls back,
-- and only a purge of the organization removes its calls.
CREATE TABLE api_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_api_request PRIMARY KEY,
    request_id UUID NOT NULL CONSTRAINT uq_api_request_request_id UNIQUE,
    organization_id BIGINT NOT NULL CONSTRAINT fk_api_request_organization REFERENCES organization (id),
    api_client_id BIGINT,
    client_name VARCHAR(80) NOT NULL,
    api_client_key_id BIGINT,
    key_prefix VARCHAR(16) NOT NULL,
    schema_bookmark_id BIGINT,
    bookmark_name VARCHAR(180),
    prediction_run_id BIGINT,
    http_status INTEGER NOT NULL CONSTRAINT ck_api_request_http_status CHECK (http_status BETWEEN 100 AND 599),
    error_code VARCHAR(40),
    duration_ms INTEGER NOT NULL CONSTRAINT ck_api_request_duration CHECK (duration_ms >= 0),
    created_at TIMESTAMPTZ NOT NULL);

CREATE INDEX idx_api_request_organization_created ON api_request (organization_id, created_at DESC);
CREATE INDEX idx_api_request_client_created ON api_request (api_client_id, created_at DESC);
-- The log is append-only, so its creation order is its physical order: retention reads a range.
CREATE INDEX idx_api_request_created ON api_request USING BRIN (created_at);

-- An API run's client is one of the run's organization; the run outlives it.
ALTER TABLE prediction_run ADD CONSTRAINT fk_prediction_run_api_client FOREIGN KEY (organization_id, api_client_id)
    REFERENCES api_client (organization_id, id) ON DELETE SET NULL (api_client_id);
CREATE INDEX idx_prediction_run_api_client ON prediction_run (organization_id, api_client_id) WHERE api_client_id IS NOT NULL;

CREATE TRIGGER trg_api_client_not_purging BEFORE INSERT ON api_client FOR EACH ROW
    EXECUTE FUNCTION refuse_under_purge('organization', 'organization_id');
CREATE TRIGGER trg_api_client_bookmark_not_purging BEFORE INSERT ON api_client_bookmark FOR EACH ROW
    EXECUTE FUNCTION refuse_under_purge('schema', 'schema_id');
