-- What the platform keeps about running itself: the audit log, notifications, alerts, the queues
-- of storage deletions and purges, and open terminal sessions.

-- The audit log records every action, by people, API clients and the system. Its actor is a
-- principal, which outlives the account; a visitor, someone who failed to sign in, or an account
-- already gone when the entry is written is none, and is named by its label alone. An entry never
-- stops the action it records. An entry outlives the organization it names, so it
-- keeps the organization's id without a foreign key, and the names as they were when it was
-- written.
CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_audit_event PRIMARY KEY,
    organization_id BIGINT,
    organization_label VARCHAR(255),
    actor_kind VARCHAR(20) NOT NULL CONSTRAINT ck_audit_actor_kind CHECK (actor_kind IN ('USER', 'SYSTEM', 'API_CLIENT', 'VISITOR')),
    actor_principal_id BIGINT,
    actor_label VARCHAR(255) NOT NULL,
    action VARCHAR(120) NOT NULL,
    target_type VARCHAR(80) NOT NULL,
    target_id VARCHAR(120),
    metadata JSONB,
    ip INET,
    request_id UUID,
    created_at TIMESTAMPTZ NOT NULL,
    -- The actor's kind is its principal's, when the event names one.
    CONSTRAINT fk_audit_event_actor FOREIGN KEY (actor_principal_id, actor_kind) REFERENCES principal (id, kind));

CREATE INDEX idx_audit_event_catalog ON audit_event (organization_id, created_at DESC, id DESC);
CREATE INDEX idx_audit_event_created ON audit_event (created_at DESC, id DESC);

-- What happened in the background, told to the person who asked for it. A notification outlives
-- what it describes, so it references neither its organization nor its target: the payload keeps
-- the labels that draw it, and the organization is null for one about the platform itself.
CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_notification PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL CONSTRAINT fk_notification_recipient REFERENCES app_user (id) ON DELETE CASCADE,
    organization_id BIGINT,
    -- What it is about follows from what happened.
    kind VARCHAR(64) NOT NULL,
    target_type VARCHAR(32) NOT NULL,
    CONSTRAINT ck_notification_kind CHECK (CASE target_type
        WHEN 'PREDICTION_JOB' THEN kind IN ('PREDICTION_JOB_COMPLETED', 'PREDICTION_JOB_COMPLETED_WITH_FAILURES', 'PREDICTION_JOB_STOPPED', 'PREDICTION_JOB_CANCELLED')
        WHEN 'MODEL' THEN kind IN ('MODEL_READY', 'MODEL_FAILED')
        WHEN 'INVITATION' THEN kind IN ('INVITATION_RECEIVED', 'INVITATION_ACCEPTED', 'INVITATION_DECLINED')
        WHEN 'ORGANIZATION' THEN kind IN ('ORGANIZATION_JOINED', 'ORGANIZATION_PURGED')
        WHEN 'REVIEW' THEN kind IN ('REVIEW_ASSIGNED', 'REVIEW_REOPENED')
        WHEN 'PURGE_JOB' THEN kind IN ('PURGE_COMPLETED', 'PURGE_FAILED')
        WHEN 'SYSTEM_ALERT' THEN kind IN ('SYSTEM_ALERT_RAISED', 'SYSTEM_ALERT_ESCALATED', 'SYSTEM_ALERT_RESOLVED')
        WHEN 'BOOKMARK' THEN kind IN ('BOOKMARK_UNPUBLISHED')
        ELSE false END),
    target_id VARCHAR(120) NOT NULL,
    payload JSONB NOT NULL,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL);

CREATE INDEX idx_notification_recipient ON notification (recipient_user_id, id DESC);
CREATE INDEX idx_notification_unread ON notification (recipient_user_id, id DESC) WHERE read_at IS NULL;
CREATE INDEX idx_notification_read_at ON notification (read_at) WHERE read_at IS NOT NULL;

-- What the platform warned its superadmins about its own load. The partial unique index keeps one
-- alert open per signal, whichever API instance raises it. trigger_value and threshold are what put
-- the alert at its severity; held_at is when any instance last saw the condition stand, which is
-- what lets it resolve only after a quiet period seen by all of them. Resolved alerts are pruned.
CREATE TABLE system_alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_system_alert PRIMARY KEY,
    signal VARCHAR(64) NOT NULL,
    severity VARCHAR(16) NOT NULL CONSTRAINT ck_system_alert_severity CHECK (severity IN ('WARNING', 'CRITICAL')),
    trigger_value DOUBLE PRECISION NOT NULL,
    threshold DOUBLE PRECISION NOT NULL,
    latest_value DOUBLE PRECISION NOT NULL,
    raised_at TIMESTAMPTZ NOT NULL,
    held_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ);

CREATE UNIQUE INDEX uq_system_alert_open ON system_alert (signal) WHERE resolved_at IS NULL;
CREATE INDEX idx_system_alert_resolved ON system_alert (resolved_at DESC) WHERE resolved_at IS NOT NULL;

-- Objects to remove from storage once nothing refers to them; workers claim a row under a lease.
-- One task per stored version of an object, or one with no version for every version of a key.
-- organization_id is which organization a deletion belongs to, for the entry that reports it
-- failing for good.
CREATE TABLE storage_deletion_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_storage_deletion_task PRIMARY KEY,
    organization_id BIGINT,
    storage_bucket VARCHAR(100) NOT NULL,
    storage_object_key VARCHAR(512) NOT NULL,
    storage_version_id VARCHAR(255),
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING'
        CONSTRAINT ck_storage_deletion_status CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CONSTRAINT ck_storage_deletion_attempts CHECK (attempts >= 0),
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    error_message TEXT,
    lease_expires_at TIMESTAMPTZ,
    lease_owner VARCHAR(128),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT uq_storage_deletion_object UNIQUE NULLS NOT DISTINCT (storage_bucket, storage_object_key, storage_version_id),
    CONSTRAINT ck_storage_deletion_claim CHECK ((status = 'RUNNING') = (lease_owner IS NOT NULL)
        AND (lease_owner IS NULL) = (lease_expires_at IS NULL)),
    CONSTRAINT ck_storage_deletion_completed CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    CONSTRAINT ck_storage_deletion_failed CHECK (status <> 'FAILED' OR error_message IS NOT NULL));

CREATE INDEX idx_storage_deletion_pending ON storage_deletion_task (next_attempt_at, id) WHERE status = 'PENDING';
CREATE INDEX idx_storage_deletion_lease ON storage_deletion_task (lease_expires_at, id) WHERE status = 'RUNNING';
CREATE INDEX idx_storage_deletion_completed ON storage_deletion_task (completed_at) WHERE status = 'COMPLETED';

-- A superadmin's cascade purge, run on the server like a bulk job: workers claim a job with
-- SELECT ... FOR UPDATE SKIP LOCKED under a lease, delete in small transactions and write down the
-- phase they reached, so a job whose worker crashed is claimed again and goes on from there. A
-- failed purge keeps its target closed until it is retried. A job outlives what it names, so it
-- references its target by plain id; who asked for it is a principal, which outlives them too.
CREATE TABLE purge_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_purge_job PRIMARY KEY,
    scope VARCHAR(16) NOT NULL CONSTRAINT ck_purge_job_scope CHECK (scope IN ('ORGANIZATION', 'USER', 'SCHEMA', 'MODEL')),
    target_id BIGINT NOT NULL,
    target_label VARCHAR(255) NOT NULL,
    -- The organization the job deletes, or the target lives in; for a user, their personal account.
    organization_id BIGINT NOT NULL,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_purge_job_created_by REFERENCES principal (id),
    -- Who asked last: the requester, or the superadmin who retried it.
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_purge_job_updated_by REFERENCES principal (id),
    status VARCHAR(16) NOT NULL CONSTRAINT ck_purge_job_status CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED')),
    phase VARCHAR(32) NOT NULL CONSTRAINT ck_purge_job_phase CHECK (phase IN (
        'PREPARE', 'JOBS', 'FEEDBACK', 'REVIEWS', 'RESULTS', 'RUNS', 'SCHEMA_CONTENT',
        'VERSIONS', 'MODELS', 'PLUGINS', 'MEMBERS', 'ACCOUNT', 'FINISH')),
    counts JSONB NOT NULL DEFAULT '{}'::jsonb,
    error_message TEXT,
    lease_owner VARCHAR(128),
    lease_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    CONSTRAINT ck_purge_job_lease CHECK ((lease_owner IS NULL) = (lease_expires_at IS NULL)
        AND (status = 'RUNNING') = (lease_owner IS NOT NULL)),
    CONSTRAINT ck_purge_job_finished CHECK ((finished_at IS NOT NULL) = (status IN ('COMPLETED', 'FAILED'))),
    CONSTRAINT ck_purge_job_error CHECK ((status = 'FAILED') = (error_message IS NOT NULL)));

CREATE UNIQUE INDEX uq_purge_job_open ON purge_job (scope, target_id) WHERE status <> 'COMPLETED';
CREATE INDEX idx_purge_job_claim ON purge_job (id) WHERE status IN ('QUEUED', 'RUNNING');

-- The snapshots a job destroys, fixed when it starts: a phase that removes what chose them cannot
-- lose the rest, and every later phase reads the same set.
CREATE TABLE purge_job_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_purge_job_version PRIMARY KEY,
    purge_job_id BIGINT NOT NULL CONSTRAINT fk_purge_job_version_job REFERENCES purge_job (id) ON DELETE CASCADE,
    schema_version_id BIGINT NOT NULL,
    CONSTRAINT uq_purge_job_version UNIQUE (purge_job_id, schema_version_id));

CREATE INDEX idx_purge_job_version_version ON purge_job_version (schema_version_id);

-- A job lists only snapshots of its target, while it runs: listing one is what lets the purge remove
-- its bindings, results and answers.
CREATE FUNCTION purge_job_version_is_its_target() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM purge_job j JOIN schema_version v ON v.id = NEW.schema_version_id
            WHERE j.id = NEW.purge_job_id AND j.status = 'RUNNING' AND v.organization_id = j.organization_id
                AND (j.scope <> 'SCHEMA' OR v.schema_id = j.target_id)
                AND (j.scope <> 'MODEL' OR EXISTS (SELECT 1 FROM schema_model_binding b
                    WHERE b.schema_version_id = v.id AND b.model_id = j.target_id))) THEN
        RAISE EXCEPTION 'A purge lists only the snapshots it destroys: violates check constraint "ck_purge_job_version_target"' USING ERRCODE = 'check_violation',
            CONSTRAINT = 'ck_purge_job_version_target', TABLE = 'purge_job_version';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_purge_job_version_target BEFORE INSERT ON purge_job_version FOR EACH ROW
    EXECUTE FUNCTION purge_job_version_is_its_target();

-- The terminal sessions the API opened that have not ended yet, by the id the terminal service gave
-- them. A session leaves this table once, however it ends (closed, its browser gone, or ended by the
-- ops agent), and that is when its end is audited, so every opened session has exactly one close.
CREATE TABLE terminal_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_terminal_session PRIMARY KEY,
    session_key VARCHAR(64) NOT NULL CONSTRAINT uq_terminal_session_key UNIQUE,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_terminal_session_created_by REFERENCES principal (id),
    service_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now());
