-- Models, the environments they run in, and plugins.

-- An environment: the Python and the distributions a bundle's lock names, plus the mlbundle release
-- that wrote it, which the runtime's builder installs once and every model needing the same files
-- shares. A row describes one environment for good, so a stored result still says what computed it
-- after the environment's files are removed. Models, results and the runtime name it by its key.
CREATE TABLE runtime_environment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_runtime_environment PRIMARY KEY,
    environment_key VARCHAR(64) NOT NULL CONSTRAINT uq_runtime_environment_key UNIQUE,
    -- mlbundle's digest of the lock (Python, packages and wheel digests).
    lock_digest VARCHAR(64),
    writer_version VARCHAR(64) NOT NULL,
    python_version VARCHAR(32) NOT NULL,
    packages JSONB NOT NULL,
    -- The bundle's canonical pylock.toml, which the builder installs.
    lock_toml TEXT,
    created_at TIMESTAMPTZ NOT NULL);

-- A model's row is written once its artifact is in object storage, the artifact's only home, and
-- verified: the row names the exact object version and the artifact's SHA-256. The artifact a row
-- names is fixed for good, so a result that names the model names the exact artifact that computed
-- it; the environment can be prepared again, so a result keeps the one that computed it.
-- lock_version is the row's optimistic lock, not a version of the model.
CREATE TABLE model (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_model PRIMARY KEY,
    lock_version BIGINT NOT NULL DEFAULT 0,
    organization_id BIGINT NOT NULL CONSTRAINT fk_model_organization REFERENCES organization (id),
    name VARCHAR(100) NOT NULL CONSTRAINT ck_model_name_present CHECK (btrim(name) <> ''),
    type VARCHAR(255) NOT NULL,
    specific_type VARCHAR(255) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    storage_bucket VARCHAR(100) NOT NULL,
    storage_object_key VARCHAR(512) NOT NULL,
    storage_version_id VARCHAR(255) NOT NULL,
    storage_etag VARCHAR(128) NOT NULL,
    -- One stored object is one model's: deleting it can never take another's artifact.
    CONSTRAINT uq_model_storage_object UNIQUE (storage_bucket, storage_object_key, storage_version_id),
    size_bytes BIGINT NOT NULL CONSTRAINT ck_model_size CHECK (size_bytes > 0),
    artifact_sha256 VARCHAR(64) NOT NULL CONSTRAINT ck_model_artifact_sha256 CHECK (artifact_sha256 ~ '^[0-9a-f]{64}$'),
    artifact_verified_at TIMESTAMPTZ NOT NULL,
    -- What the model's bundle says about it: its manifest as uploaded, and the feature importances
    -- the runtime reads from its structure (absent for models without one).
    input_schema JSONB NOT NULL,
    bundle_manifest JSONB NOT NULL DEFAULT '{}'::jsonb,
    feature_importances JSONB,
    environment_key VARCHAR(64) NOT NULL CONSTRAINT fk_model_environment REFERENCES runtime_environment (environment_key),
    archived_at TIMESTAMPTZ,
    -- Set under the model's lock when a purge of it is asked for, and never cleared.
    purging_at TIMESTAMPTZ,
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_model_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_model_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_model_org_id UNIQUE (organization_id, id));

-- A name is one model's in its organization, whatever its case.
CREATE UNIQUE INDEX uq_model_name_org ON model (organization_id, lower(name));
CREATE INDEX idx_search_model_name_trgm ON model USING GIN (lower(name) gin_trgm_ops);
CREATE INDEX idx_search_model_file_trgm ON model USING GIN (lower(file_name) gin_trgm_ops);

-- A model's artifact is written once; what is learned about it later (its runtime state) may change.
CREATE TRIGGER trg_model_artifact_fixed BEFORE UPDATE OF file_name, storage_bucket, storage_object_key,
    storage_version_id, storage_etag, size_bytes, artifact_sha256 ON model FOR EACH ROW
    WHEN ((OLD.file_name, OLD.storage_bucket, OLD.storage_object_key, OLD.storage_version_id, OLD.storage_etag,
        OLD.size_bytes, OLD.artifact_sha256)
        IS DISTINCT FROM (NEW.file_name, NEW.storage_bucket, NEW.storage_object_key, NEW.storage_version_id,
        NEW.storage_etag, NEW.size_bytes, NEW.artifact_sha256))
    EXECUTE FUNCTION refuse_change('ck_model_artifact_fixed');

-- Getting a model ready to run, written with the model: its environment is built and the model
-- loaded there (READY); until then it is PREPARING, claimed by one API instance at a time under a
-- lease, or FAILED with the reason. After an attempt that failed in a way worth retrying it waits,
-- unclaimed, until next_attempt_at.
CREATE TABLE model_preparation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_model_preparation PRIMARY KEY,
    model_id BIGINT NOT NULL CONSTRAINT uq_model_preparation_model UNIQUE
        CONSTRAINT fk_model_preparation_model REFERENCES model (id) ON DELETE CASCADE,
    state VARCHAR(16) NOT NULL CONSTRAINT ck_model_preparation_state CHECK (state IN ('PREPARING', 'READY', 'FAILED')),
    error_message TEXT,
    attempts INTEGER NOT NULL DEFAULT 0 CONSTRAINT ck_model_preparation_attempts CHECK (attempts >= 0),
    lease_owner VARCHAR(128),
    lease_expires_at TIMESTAMPTZ,
    next_attempt_at TIMESTAMPTZ,
    CONSTRAINT ck_model_preparation_lease CHECK ((lease_owner IS NULL) = (lease_expires_at IS NULL)
        AND (state = 'PREPARING' OR (lease_owner IS NULL AND next_attempt_at IS NULL))),
    CONSTRAINT ck_model_preparation_failed CHECK ((state = 'FAILED') = (error_message IS NOT NULL) OR state = 'PREPARING'));

CREATE INDEX idx_model_preparation_preparing ON model_preparation (model_id) WHERE state = 'PREPARING';

-- A plugin is stored as an object with its metadata row, in one transaction. public_id is the
-- random id its object is stored under, and how the API names the plugin.
CREATE TABLE plugin_metadata (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_plugin_metadata PRIMARY KEY,
    public_id VARCHAR(64) NOT NULL CONSTRAINT uq_plugin_metadata_public_id UNIQUE,
    organization_id BIGINT NOT NULL CONSTRAINT fk_plugin_metadata_org REFERENCES organization (id),
    plugin_type VARCHAR(32) NOT NULL CONSTRAINT ck_plugin_metadata_type CHECK (plugin_type IN ('field', 'report')),
    kind VARCHAR(180),
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    storage_bucket VARCHAR(100) NOT NULL,
    storage_object_key VARCHAR(512) NOT NULL,
    storage_version_id VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL CONSTRAINT ck_plugin_metadata_size CHECK (size_bytes > 0),
    artifact_sha256 VARCHAR(64) NOT NULL CONSTRAINT ck_plugin_metadata_sha256 CHECK (artifact_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT uq_plugin_metadata_storage_object UNIQUE (storage_bucket, storage_object_key, storage_version_id),
    CONSTRAINT uq_plugin_metadata_org_id UNIQUE (organization_id, id),
    created_by_principal_id BIGINT NOT NULL CONSTRAINT fk_plugin_metadata_created_by REFERENCES principal (id),
    updated_by_principal_id BIGINT NOT NULL CONSTRAINT fk_plugin_metadata_updated_by REFERENCES principal (id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL);

-- A plugin's identity, kind and stored key are fixed; anonymizing its author's name writes a new
-- version of the same object (version, size and digest change, the code does not).
CREATE TRIGGER trg_plugin_metadata_fixed BEFORE UPDATE OF public_id, organization_id, plugin_type, kind, storage_object_key
    ON plugin_metadata FOR EACH ROW
    WHEN ((OLD.public_id, OLD.organization_id, OLD.plugin_type, OLD.kind, OLD.storage_object_key)
        IS DISTINCT FROM (NEW.public_id, NEW.organization_id, NEW.plugin_type, NEW.kind, NEW.storage_object_key))
    EXECUTE FUNCTION refuse_change('ck_plugin_metadata_fixed');

CREATE INDEX idx_plugin_catalog ON plugin_metadata (organization_id, updated_at DESC, id);
CREATE INDEX idx_search_plugin_file_trgm ON plugin_metadata USING GIN (lower(file_name) gin_trgm_ops);
CREATE INDEX idx_search_plugin_kind_trgm ON plugin_metadata USING GIN (lower(kind) gin_trgm_ops);

CREATE TRIGGER trg_model_not_purging BEFORE INSERT ON model FOR EACH ROW
    EXECUTE FUNCTION refuse_under_purge('organization', 'organization_id');
CREATE TRIGGER trg_plugin_metadata_not_purging BEFORE INSERT ON plugin_metadata FOR EACH ROW
    EXECUTE FUNCTION refuse_under_purge('organization', 'organization_id');
